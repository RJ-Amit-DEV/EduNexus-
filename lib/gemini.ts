import { GoogleGenAI } from "@google/genai";

const apiKey = process.env.GEMINI_API_KEY;
const ai = apiKey ? new GoogleGenAI({ apiKey }) : null;

// Helper to sanitize JSON
function parseJsonSafe(text: string): any {
  try {
    const clean = text.replace(/```json/gi, "").replace(/```/g, "").trim();
    return JSON.parse(clean);
  } catch {
    return null;
  }
}

// 1. Adaptive Study Plan Generator
export async function generateStudyPlan(subject: string, targetGoal: string, hoursPerWeek: number) {
  const fallback = {
    title: `Personalized AI Roadmap: ${subject}`,
    targetGoal,
    weeklyHours: hoursPerWeek,
    modules: [
      {
        week: 1,
        topic: "Foundational Principles & Core Diagnostics",
        tasks: [
          `Review core fundamentals of ${subject}`,
          "Complete baseline diagnostic quiz (Target: >85%)",
          "Identify and map weak topics into revision cards",
        ],
        estimatedHours: Math.max(2, Math.round(hoursPerWeek * 0.35)),
      },
      {
        week: 2,
        topic: "Applied Problem Solving & Scenario Drills",
        tasks: [
          "Solve 10 multi-step conceptual problem sets",
          "Attend virtual peer discussion / doubt session",
          "Perform mid-way timed speed assessment",
        ],
        estimatedHours: Math.max(2, Math.round(hoursPerWeek * 0.4)),
      },
      {
        week: 3,
        topic: "Exam Readiness, Timed Mocks & Mastery",
        tasks: [
          "Complete full-length timed mock examination",
          "Review error log with AI Tutor",
          "Final formula mastery and summary sheet creation",
        ],
        estimatedHours: Math.max(2, Math.round(hoursPerWeek * 0.25)),
      },
    ],
    aiNote: "Generated by EduNexus Adaptive Learning Engine.",
  };

  if (!ai || !apiKey) return fallback;

  try {
    const prompt = `You are EduNexus AI Study Planner. Create a structured 3-week study roadmap in JSON format for a student studying "${subject}" with the goal "${targetGoal}". The student can dedicate ${hoursPerWeek} hours/week.
Return ONLY raw JSON with keys: "title", "targetGoal", "weeklyHours", "modules" (array of { "week": number, "topic": string, "tasks": string[], "estimatedHours": number }), "aiNote".`;

    const res = await ai.models.generateContent({
      model: "gemini-3.8-flash",
      contents: prompt,
    });

    const parsed = parseJsonSafe(res.text || "");
    return parsed || fallback;
  } catch (error) {
    console.error("Gemini study plan error, using structured fallback:", error);
    return fallback;
  }
}

